fn is_identifier(character: char) -> bool {
    character.is_alphanumeric() || character == '_'
}

/// Byte offsets where `pattern` occurs in `line` without running into a longer
/// identifier: `fs::symlink` is not `fs::symlink_metadata`, `nix` is not `Unix`.
/// A side of the pattern that is punctuation needs no boundary.
fn word_positions(line: &str, pattern: &str) -> Vec<usize> {
    let open_start = pattern.starts_with(is_identifier);
    let open_end = pattern.ends_with(is_identifier);
    line.match_indices(pattern)
        .filter(|(start, _)| {
            let before = line[..*start].chars().next_back();
            let after = line[start + pattern.len()..].chars().next();
            !(open_start && before.is_some_and(is_identifier))
                && !(open_end && after.is_some_and(is_identifier))
        })
        .map(|(start, _)| start)
        .collect()
}

/// A line with its `//` comment removed. String literals containing `//` lose
/// their tail too, which can only hide text, never invent a match.
fn code(line: &str) -> &str {
    line.find("//").map_or(line, |comment| &line[..comment])
}

/// The production part of a source file: everything before its first
/// column-zero `#[cfg(test)]`. rustfmt (enforced by `cargo fmt --check`) puts
/// every item of a module body below column zero, so a column-zero line after
/// that point is either a test module's own attribute, header or closing brace,
/// or production code placed after the tests — which is reported, not trusted.
fn production_lines(path: &str, text: &str) -> Result<Vec<(usize, String)>, String> {
    let lines: Vec<&str> = text.lines().collect();
    let Some(cut) = lines.iter().position(|line| *line == "#[cfg(test)]") else {
        return Ok(lines
            .iter()
            .enumerate()
            .map(|(index, line)| (index + 1, line.to_string()))
            .collect());
    };
    let mut cfg_test = false;
    for (index, line) in lines.iter().enumerate().skip(cut) {
        let top_level = !line.is_empty() && !line.starts_with([' ', '\t']);
        if !top_level || line.starts_with("//") || *line == "}" {
            continue;
        }
        if *line == "#[cfg(test)]" {
            cfg_test = true;
        } else if line.starts_with("#[") {
            // Further attributes of the same item keep the `cfg(test)` in force.
        } else if line.starts_with("mod ") && line.ends_with('{') && cfg_test {
            cfg_test = false;
        } else {
            return Err(format!(
                "{path}:{}: column-zero code after the test region is not \
                 `#[cfg(test)]`-gated: {line}",
                index + 1
            ));
        }
    }
    Ok(lines[..cut]
        .iter()
        .enumerate()
        .map(|(index, line)| (index + 1, line.to_string()))
        .collect())
}

/// Every forbidden construct in the production part of `text`.
fn violations(path: &str, text: &str) -> Vec<String> {
    let lines = match production_lines(path, text) {
        Ok(lines) => lines,
        Err(error) => return vec![error],
    };
    let mut found = Vec::new();
    for (number, line) in &lines {
        let line = code(line);
        let mut report = |what: &str, why: &str| {
            found.push(format!(
                "{path}:{number}: `{what}` ({why}): {}",
                line.trim()
            ));
        };
        for (word, why) in FORBIDDEN_WORDS {
            if !word_positions(line, word).is_empty() {
                report(word, why);
            }
        }
        for (name, why) in FORBIDDEN_CALLS {
            let called = word_positions(line, name)
                .into_iter()
                .any(|start| line[start + name.len()..].trim_start().starts_with('('));
            if called {
                report(name, why);
            }
        }
        for (text, why) in FORBIDDEN_TEXT {
            if !word_positions(line, text).is_empty() {
                report(text, why);
            }
        }
        for (start, _) in line.match_indices("SignalKind::") {
            if !RECEIVED_SIGNALS
                .iter()
                .any(|allowed| line[start..].starts_with(allowed))
            {
                report(
                    "SignalKind",
                    "a signal other than SIGINT, SIGTERM or SIGUSR1",
                );
            }
        }
    }
    found
}

fn crate_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn rust_files(directory: &Path, into: &mut Vec<PathBuf>) {
    let mut entries: Vec<PathBuf> = std::fs::read_dir(directory)
        .expect("the source directory is readable")
        .map(|entry| entry.expect("a readable entry").path())
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            rust_files(&path, into);
        } else if path.extension().is_some_and(|extension| extension == "rs") {
            into.push(path);
        }
    }
}

/// The audit itself is not vacuous: each kind of construct it exists to catch is
/// caught, test code is not production code, and code hidden after a test
/// module is refused rather than skipped.
#[test]
fn the_source_audit_catches_what_it_is_for() {
    for (snippet, expected) in [
        ("let child = std::process::Command::new(\"x\");", "Command"),
        ("tokio::process::Command::new(\"x\");", "tokio::process"),
        ("let _ = worker.kill();", "kill"),
        ("unsafe { libc::kill(pid, 15) };", "unsafe"),
        ("let _ = nix::sys::signal::kill(pid, None);", "nix"),
        (
            "fs::write(\"/proc/1/oom_score_adj\", \"1000\")?;",
            "fs::write",
        ),
        (
            "std::fs::OpenOptions::new().write(true).open(\"/sys/fs/cgroup/x/cgroup.procs\")?;",
            "OpenOptions",
        ),
        (
            "session.create_terminal_node(id, spec)?;",
            "create_terminal_node",
        ),
        ("session.on(TABLE, ACTIVATE, |_| {});", ".on("),
        (
            "session.on_result(TABLE, ACTIVATE, |_, _| Ok(()));",
            ".on_result(",
        ),
        ("let mut hup = signal(SignalKind::hangup())?;", "SignalKind"),
        ("setpriority(0, pid, 19);", "setpriority"),
        ("sched_setaffinity (pid, size, set);", "sched_setaffinity"),
    ] {
        let found = violations("snippet.rs", snippet);
        assert!(
            found
                .iter()
                .any(|violation| violation.contains(&format!("`{expected}`"))),
            "{snippet:?} was not reported as {expected:?}: {found:?}"
        );
    }
    for innocent in [
        "// a comment may say kill(2) and Command",
        "let [user, nice, system] = counts;",
        "let _ = write!(text, \"{byte:02x}\");",
        "let id = std::process::id();",
        "let mut term = signal(SignalKind::terminate())?;",
        "connections.spawn(poll(view, source, session, interval, token));",
        "let token = shutdown.child_token();",
        "let kind = std::fs::symlink_metadata(&path)?;",
    ] {
        assert_eq!(violations("snippet.rs", innocent), Vec::<String>::new());
    }
    let tested =
        "pub fn live() {}\n#[cfg(test)]\nmod tests {\n    fn t() { Command::new(\"x\"); }\n}\n";
    assert_eq!(violations("tested.rs", tested), Vec::<String>::new());
    let hidden = "pub fn live() {}\n#[cfg(test)]\nmod tests {\n}\n\npub fn late() {}\n";
    assert!(violations("hidden.rs", hidden)[0].contains("not `#[cfg(test)]`-gated"));
    let ungated = "#[cfg(test)]\nmod tests {\n}\nmod more {\n}\n";
    assert!(violations("ungated.rs", ungated)[0].contains("mod more"));
}

#[test]
fn no_production_source_can_signal_or_reconfigure_a_process() {
    let root = crate_root();
    let mut files = Vec::new();
    rust_files(&root.join("src"), &mut files);
    assert!(
        files.iter().any(|path| path.ends_with("src/main.rs")),
        "the audit must cover the binary's entry point"
    );
    let mut found = Vec::new();
    let mut audited = Vec::new();
    let mut receivers = 0;
    for path in &files {
        let text = std::fs::read_to_string(path).expect("a readable source file");
        let name = path
            .strip_prefix(&root)
            .unwrap_or(path)
            .display()
            .to_string();
        let production = production_lines(&name, &text).unwrap_or_else(|error| panic!("{error}"));
        receivers += production
            .iter()
            .map(|(_, line)| code(line).matches("SignalKind::").count())
            .sum::<usize>();
        audited.push(format!("{name}:{}", production.len()));
        found.extend(violations(&name, &text));
    }
    assert!(
        found.is_empty(),
        "process control in production code:\n{}",
        found.join("\n")
    );
    // The exceptions, stated: `main` receives SIGINT and SIGTERM to remove its
    // own socket, and SIGUSR1 only under `--smoke-fixture`, to retitle the shell.
    assert_eq!(receivers, RECEIVED_SIGNALS.len());

    // The manifest: only the runtime, no native library, no build script.
    let manifest =
        std::fs::read_to_string(root.join("Cargo.toml")).expect("the manifest is readable");
    let mut section = String::new();
    let mut dependencies = BTreeSet::new();
    for line in manifest.lines().map(str::trim) {
        if line.starts_with('[') {
            section = line.to_string();
            assert!(
                !section.contains("build-dependencies") && !section.starts_with("[target"),
                "unexpected manifest section {section}"
            );
            continue;
        }
        assert!(
            !line.starts_with("build") && !line.starts_with("links"),
            "the package may not run a build script or link a native library: {line}"
        );
        if section == "[dependencies]" {
            if let Some((name, _)) = line.split_once('=') {
                dependencies.insert(name.trim().to_string());
            }
        }
    }
    let allowed: BTreeSet<String> = ALLOWED_DEPENDENCIES
        .iter()
        .map(|name| name.to_string())
        .collect();
    assert_eq!(dependencies, allowed, "direct dependencies changed");
    assert!(!root.join("build.rs").exists(), "no build script");
    println!(
        "PX-008 source audit: {} files, production lines per file {audited:?}; \
         0 violations; signal receivers {RECEIVED_SIGNALS:?}; dependencies {dependencies:?}",
        files.len()
    );
}

