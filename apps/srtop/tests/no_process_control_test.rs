//! PX-008, the R0 release gate: no code path of this application can signal or
//! reconfigure a process (D1 §4 invariants 1 and 18, §7.7, §24; D2 T21).
//!
//! Two independent checks, both repeatable and both run by `cargo test`:
//!
//! * **Sources.** Every production line of `src/` is searched for the ways Rust
//!   code can reach another process: spawning one (`Command`, `Child`,
//!   `tokio::process`), calling the C library or the kernel directly (`unsafe`,
//!   `extern`, `libc`, `nix`, `syscall`), signalling, tracing, re-prioritizing or
//!   re-limiting one by name (`kill(`, `ptrace(`, `setpriority(`, …), writing
//!   any file (`OpenOptions`, `File::create`, `fs::write`, … — there is no other
//!   way to reach `/proc/<pid>/*`, `/sys/fs/cgroup` or `/proc/sys`), the runtime's
//!   PTY facility (the one runtime path that spawns and signals children), and
//!   every way client input reaches application code (`Session::on`,
//!   `on_result`, `on_text_edit`, a model range provider). The manifest must name
//!   only the SRUI runtime and tokio, with no build script.
//!   The only signal API allowed is receiving SIGINT, SIGTERM and the
//!   `--smoke-fixture` SIGUSR1 trigger.
//! * **Binary.** The dynamic symbols the built `srtop` imports are listed with
//!   `nm`. No process-creation, process-reconfiguration or targeted-signal
//!   function may be among them. `kill`, `waitpid` and `waitid` are imported, and
//!   attributed: they are the runtime PTY manager's teardown of PTY children it
//!   spawned itself, and its spawn path is absent from the binary (no `fork`,
//!   `exec*`, `posix_spawn*` or `clone` is imported) and never called by `src/`.
//!
//! What neither can prove: the behaviour of dependencies beyond their imported
//! symbols; a raw `syscall(2)` made by a dependency (Linux imports `syscall` for
//! std's futex, `statx` and pidfd use — `src/` cannot make one without the
//! `unsafe` the source check forbids); code generated by a dependency's macro;
//! or what another program may do to the same processes.
