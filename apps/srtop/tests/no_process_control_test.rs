#[test]
fn the_binary_imports_no_process_creation_signalling_or_reconfiguration_function() {
    let binary = env!("CARGO_BIN_EXE_srtop");
    let arguments: &[&str] = if cfg!(target_os = "macos") {
        &["-u"]
    } else {
        &["-D", "--undefined-only"]
    };
    let output = Command::new("nm")
        .args(arguments)
        .arg(binary)
        .stdin(Stdio::null())
        .stderr(Stdio::piped())
        .output()
        .expect("nm is required for the import audit; it is never skipped");
    assert!(
        output.status.success(),
        "nm failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let imports: BTreeSet<String> = String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| line.split_whitespace().last())
        .map(|symbol| {
            let symbol = symbol.split('@').next().unwrap_or(symbol);
            let symbol = if cfg!(target_os = "macos") {
                symbol.strip_prefix('_').unwrap_or(symbol)
            } else {
                symbol
            };
            symbol.to_string()
        })
        .collect();
    assert!(
        imports.contains("read") && imports.len() > 20,
        "implausible import list from nm: {imports:?}"
    );
    let forbidden: Vec<&str> = FORBIDDEN_IMPORTS
        .iter()
        .copied()
        .filter(|symbol| imports.contains(*symbol))
        .collect();
    assert!(
        forbidden.is_empty(),
        "srtop imports process-control functions: {forbidden:?}"
    );
    let attributed: Vec<String> = ATTRIBUTED_IMPORTS
        .iter()
        .filter(|(symbol, _)| imports.contains(*symbol))
        .map(|(symbol, reason)| format!("{symbol}: {reason}"))
        .collect();
    println!(
        "PX-008 import audit ({}): {} imported symbols; forbidden present: none; \
         attributed: {attributed:?}; all: {imports:?}",
        std::env::consts::OS,
        imports.len()
    );
}
