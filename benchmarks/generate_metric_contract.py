#!/usr/bin/env python3
"""Generate cross-language constants for the benchmark metric contract."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from benchmarks.contract import CONTRACT, CONTRACT_SHA256

ROOT = Path(__file__).resolve().parent.parent
SWIFT_OUTPUT = (
    ROOT / "client-macos/Benchmarks/MetricContract.generated.swift"
)
RUST_OUTPUT = (
    ROOT / "server-rust/benchmark-driver/src/metric_contract.generated.rs"
)


def _quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_swift() -> str:
    semantics = CONTRACT["percentile_semantics"]
    return f"""// Generated by benchmarks/generate_metric_contract.py. Do not edit.

enum BenchmarkMetricContract {{
    static let schemaVersion: Int = {CONTRACT["schema_version"]}
    static let sha256: String = {_quoted(CONTRACT_SHA256)}
    static let percentileRank: String = {_quoted(semantics["rank"])}
    static let percentileIndex: String = {_quoted(semantics["index"])}
    static let percentileEmpty: String = {_quoted(semantics["empty"])}
    static let percentileValues: String = {_quoted(semantics["values"])}
    static let percentileFraction: String = {_quoted(semantics["fraction"])}
}}
"""


def render_rust() -> str:
    semantics = CONTRACT["percentile_semantics"]
    return f"""// Generated by benchmarks/generate_metric_contract.py. Do not edit.

#![allow(dead_code)]

pub(crate) const SCHEMA_VERSION: u32 = {CONTRACT["schema_version"]};
pub(crate) const CONTRACT_SHA256: &str =\n    {_quoted(CONTRACT_SHA256)};
pub(crate) const PERCENTILE_RANK: &str = {_quoted(semantics["rank"])};
pub(crate) const PERCENTILE_INDEX: &str = {_quoted(semantics["index"])};
pub(crate) const PERCENTILE_EMPTY: &str = {_quoted(semantics["empty"])};
pub(crate) const PERCENTILE_VALUES: &str = {_quoted(semantics["values"])};
pub(crate) const PERCENTILE_FRACTION: &str = {_quoted(semantics["fraction"])};
"""


def generate(*, check: bool) -> int:
    stale: list[Path] = []
    for path, content in (
        (SWIFT_OUTPUT, render_swift()),
        (RUST_OUTPUT, render_rust()),
    ):
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            path.write_text(content, encoding="utf-8")
    if stale:
        print(
            "stale metric-contract descriptor(s): "
            + ", ".join(str(path.relative_to(ROOT)) for path in stale),
            file=sys.stderr,
        )
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if checked-in descriptors differ from the canonical contract",
    )
    args = parser.parse_args(argv)
    return generate(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
